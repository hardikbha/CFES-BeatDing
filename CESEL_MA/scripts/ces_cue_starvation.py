"""Per-group cue-starvation table of a CESel checkpoint (user request 25 Oct; CPU, from saved scores, no inference).

  python scripts/ces_cue_starvation.py --run runs/ffpp_B0_s7 --out_dir results/b0_cue_starvation [--tag B0]

Inputs: <run>/eval/{val,ffpp_test,dfdc,celebdf,dfd}_scores.npz (scripts/evaluate_ces.py, with s_k) and <run>/<ckpt>
(head weights + CES state). For FF++ VALIDATION and each TEST set, per group (the set's Ding scheme: 8 groups, or 6
on Celeb-DF / DFD) x class (real / fake) x cue k:
  n, mean utility u_gk (the L_sens / L_floor definition: u_ik = m(s_i, y_i) - m(s_i^(-k), y_i), training margin,
  training replacement rule incl. the same-group real-cue EMA mean for unpaired fakes; scripts/cue_stats.py),
  percentile bootstrap 95% CI of the cell mean (images resampled within the cell, B = 1000, rng seed 0),
  deficit = u_pool_k - u_gk with u_pool_k = mean over every image of that class in the set (all groups),
  share of cue k in the group's total evidence: share_pos = max(u_gk, 0) / sum_k' max(u_gk', 0) (positive utility
  only; NaN when no cue has positive mean utility) and share_signed = u_gk / sum_k' u_gk'.
Labels are used (analysis only; nothing here selects a model). Writes <out_dir>/<tag>_cue_starvation.csv and .md.
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)

import cue_stats as C  # noqa: E402
from cfes.ces_model import CUES  # noqa: E402
from cfes.config import load_config  # noqa: E402
from cfes.data import SCHEMES  # noqa: E402

NAMES = {"val": "FF++ val", "ffpp_test": "FF++ test", "dfdc": "DFDC", "celebdf": "Celeb-DF", "dfd": "DFD"}


def boot_ci(x, B, rng, chunk=100):
    n = len(x)
    means = []
    for i in range(0, B, chunk):
        b = min(chunk, B - i)
        means.append(x[rng.integers(0, n, (b, n))].mean(1))
    m = np.concatenate(means)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--ckpt", default="best.pt")
    ap.add_argument("--out_dir", required=True)
    ap.add_argument("--tag", default=None)
    ap.add_argument("--B", type=int, default=1000)
    a = ap.parse_args()
    tag = a.tag or os.path.basename(os.path.normpath(a.run))
    ev = os.path.join(a.run, "eval")
    cfg = load_config(os.path.join(a.run, "config.yaml"))
    ces = cfg.get("ces", {})
    tsch = cfg["data"]["train"].get("scheme", "eight")
    sets = {"val": ("eight", os.path.join(ev, "val_scores.npz"))}
    for k, sp in cfg["eval"]["test_sets"].items():
        sets[k] = (sp.get("scheme", "eight"), os.path.join(ev, f"{k}_scores.npz"))
    ref = C.load_ref(os.path.join(a.run, a.ckpt))
    rng = np.random.default_rng(0)
    rows = []
    for name, (sch, f) in sets.items():
        if not os.path.exists(f):
            print(f"skip {name}: {f} missing")
            continue
        d = np.load(f, allow_pickle=True)
        s, sk, y, g = d["logit"].astype(np.float64), d["s_k"].astype(np.float64), d["label"].astype(int), d["group"].astype(int)
        u = C.utilities(s, sk, y, C.to_train_groups(g, sch, tsch), ref, ces)
        for c in (0, 1):
            pool = u[y == c].mean(0)
            for gi, gname in enumerate(SCHEMES[sch]):
                m = (y == c) & (g == gi)
                n = int(m.sum())
                if n == 0:
                    continue
                ug = u[m].mean(0)
                pos = np.maximum(ug, 0)
                for k, cue in enumerate(CUES):
                    lo, hi = boot_ci(u[m, k], a.B, rng) if n > 1 else (float("nan"), float("nan"))
                    rows.append({"model": tag, "set": name, "scheme": sch, "group": gname, "class": "real" if c == 0 else "fake",
                                 "cue": cue, "n": n, "u_mean": float(ug[k]), "ci_lo": lo, "ci_hi": hi,
                                 "u_pool": float(pool[k]), "deficit": float(pool[k] - ug[k]),
                                 "share_pos": float(pos[k] / pos.sum()) if pos.sum() > 0 else float("nan"),
                                 "share_signed": float(ug[k] / ug.sum()) if abs(ug.sum()) > 1e-12 else float("nan")})
    os.makedirs(a.out_dir, exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(a.out_dir, f"{tag}_cue_starvation.csv"), index=False, float_format="%.5g")
    L = [f"# Per-group cue starvation: {tag} ({a.ckpt})", "",
         f"Generated by scripts/ces_cue_starvation.py from `{os.path.abspath(a.run)}`. u = removal utility in asinh-margin "
         "units (L_sens / L_floor definition, training replacement rule: reals -> fake EMA class mean, fakes -> real-cue "
         "EMA mean of their own group). Cell: mean u [95% bootstrap CI] (deficit = pooled class mean - group mean; "
         "positive = the group gets LESS evidence from this cue than the class as a whole). share = positive-utility "
         f"share of the cue in the group's evidence. B = {a.B}. Fakes on six-group sets use the eight-group baseline "
         "mapped by group name.", ""]
    for name in sets:
        sub = df[df["set"] == name] if len(df) else df
        if not len(sub):
            continue
        for cls in ("real", "fake"):
            t = sub[sub["class"] == cls]
            L += [f"## {NAMES.get(name, name)}, {cls}s", "",
                  "| group | n | " + " | ".join(f"{c}: u [CI] (deficit)" for c in CUES) + " | " +
                  " | ".join(f"share {c}" for c in CUES) + " |", "|---|---|" + "---|" * (2 * len(CUES))]
            for gname in SCHEMES[t["scheme"].iloc[0]] if len(t) else []:
                r = t[t["group"] == gname].set_index("cue")
                if not len(r):
                    continue
                cells = [f"{r.loc[c, 'u_mean']:.3f} [{r.loc[c, 'ci_lo']:.3f}, {r.loc[c, 'ci_hi']:.3f}] ({r.loc[c, 'deficit']:+.3f})"
                         for c in CUES]
                sh = [f"{100 * r.loc[c, 'share_pos']:.0f}%" if np.isfinite(r.loc[c, "share_pos"]) else "-" for c in CUES]
                L.append(f"| {gname} | {int(r['n'].iloc[0])} | " + " | ".join(cells) + " | " + " | ".join(sh) + " |")
            p = t.drop_duplicates("cue").set_index("cue")
            L.append("| pooled | " + str(int((sub[(sub['class'] == cls) & (sub['cue'] == CUES[0])]['n']).sum())) + " | " +
                     " | ".join(f"{p.loc[c, 'u_pool']:.3f}" for c in CUES) + " |" + " |" * len(CUES))
            L.append("")
    open(os.path.join(a.out_dir, f"{tag}_cue_starvation.md"), "w").write("\n".join(L) + "\n")
    json.dump({"run": os.path.abspath(a.run), "ckpt": a.ckpt, "rows": len(df)},
              open(os.path.join(a.out_dir, f"{tag}_cue_starvation.done.json"), "w"))
    print(f"wrote {len(df)} rows -> {a.out_dir}/{tag}_cue_starvation.{{csv,md}}")


if __name__ == "__main__":
    main()
