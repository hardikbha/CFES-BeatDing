import numpy as np
import pandas as pd

R = "/home/sachin.chaudhary/ICLR_2027/research/cvpr_readiness/r20261009"
V = f"{R}/agents/DEMO_AXES"
LF = f"{V}/labels_fairface"
O = f"{V}/results/fairforensics_ids"
IDS8 = ["MYW", "FYW", "MAW", "FAW", "MAN", "FAN", "MYN", "FYN"]
SETN = {"ffpp_test": "FF++ test", "dfdc": "DFDC", "celebdf": "Celeb-DF", "dfd": "DFD", "ff2_test": "FF2-public TEST"}
HEAD = ["CFES-D", "arm C", "control (det-only)", "Ding repro (SFD+GDA)", "CESel B0"]
